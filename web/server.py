#!/usr/bin/env python3
"""Minimal static server for the Kanto First web player.

Python 3 standard library only, no state, no configuration files.  It serves an
explicit allowlist of files (read into memory at startup) plus the ROM passed
with --rom.  Every other path is a 404: there is no directory listing and the
URL is never turned into a filesystem path, so path traversal has nothing to
traverse.

    python3 server.py --rom kanto-first.gbc
    python3 server.py --rom kanto-first.gbc --link     # also the LK1d link relay at /link

TLS and any public exposure are the host's job -- put this behind a reverse
proxy (nginx, Caddy, Cloudflare Tunnel) rather than binding it to 0.0.0.0.
"""

import argparse
import http.server
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

# published path -> (file relative to this directory, content type, cacheable)
# cacheable: False -> "no-store", True -> "max-age=3600", or a literal
# Cache-Control value (sw.js: "no-cache", so every update check revalidates).
STATIC = {
    "/": ("index.html", "text/html; charset=utf-8", False),
    "/index.html": ("index.html", "text/html; charset=utf-8", False),
    "/app.js": ("app.js", "text/javascript; charset=utf-8", False),
    "/style.css": ("style.css", "text/css; charset=utf-8", False),
    # offline / home-screen support: offline.js registers sw.js, which is
    # GENERATED by `make crystal` (web/gen_sw.py); without it, a 404 and the
    # page simply runs online-only.
    "/offline.js": ("offline.js", "text/javascript; charset=utf-8", False),
    "/sw.js": ("sw.js", "text/javascript; charset=utf-8", "no-cache"),
    # the save editor
    "/edit": ("edit.html", "text/html; charset=utf-8", False),
    "/edit.html": ("edit.html", "text/html; charset=utf-8", False),
    "/edit.js": ("edit.js", "text/javascript; charset=utf-8", False),
    "/tables.json": ("tables.json", "application/json; charset=utf-8", False),
    "/manifest.webmanifest": ("manifest.webmanifest", "application/manifest+json", True),
    "/icon-192.png": ("icon-192.png", "image/png", True),
    "/icon-512.png": ("icon-512.png", "image/png", True),
    # binjgb, the emulator core (MIT).  binjgb.wasm MUST be served as
    # application/wasm or WebAssembly.instantiateStreaming refuses it.
    "/vendor/binjgb/binjgb.js": ("vendor/binjgb/binjgb.js", "text/javascript; charset=utf-8", True),
    "/vendor/binjgb/binjgb.wasm": ("vendor/binjgb/binjgb.wasm", "application/wasm", True),
    "/vendor/binjgb/LICENSE": ("vendor/binjgb/LICENSE", "text/plain; charset=utf-8", True),
    "/vendor/binjgb/LICENSE.gbstudio": ("vendor/binjgb/LICENSE.gbstudio", "text/plain; charset=utf-8", True),
    "/vendor/binjgb/VERSION.txt": ("vendor/binjgb/VERSION.txt", "text/plain; charset=utf-8", True),
}

ROM_PATH = "/kanto-first.gbc"

# The save editor's preset saves.  These are generated (scripts/gen_presets.py
# in the helper repo), so the file names are not known here -- the directory is
# scanned ONCE at startup and turned into ordinary allowlist entries.  Nothing
# is read from disk per request, and only these two extensions are picked up.
PRESET_DIR = "presets"
PRESET_TYPES = {".sav": "application/octet-stream", ".json": "application/json; charset=utf-8"}


def preset_entries():
    """presets/*.sav + presets/manifest.json -> allowlist entries."""
    out = {}
    root = os.path.join(HERE, PRESET_DIR)
    if not os.path.isdir(root):
        return out
    for name in sorted(os.listdir(root)):
        ctype = PRESET_TYPES.get(os.path.splitext(name)[1].lower())
        if ctype is None or not os.path.isfile(os.path.join(root, name)):
            continue
        out["/%s/%s" % (PRESET_DIR, name)] = ("%s/%s" % (PRESET_DIR, name), ctype, False)
    return out


def load_files(rom_file):
    """Read the allowlist and the ROM into memory once, at startup."""
    served = {}
    allowed = dict(STATIC)
    allowed.update(preset_entries())
    for url, (rel, ctype, cacheable) in allowed.items():
        path = os.path.join(HERE, rel)
        if not os.path.isfile(path):
            if url == "/":
                sys.exit("missing required file: %s" % path)
            continue
        with open(path, "rb") as handle:
            served[url] = (handle.read(), ctype, cacheable)
    if not os.path.isfile(rom_file):
        sys.exit("no ROM at %s -- pass --rom /path/to/kanto-first.gbc" % rom_file)
    with open(rom_file, "rb") as handle:
        served[ROM_PATH] = (handle.read(), "application/octet-stream", False)
    return served


class Handler(http.server.BaseHTTPRequestHandler):
    server_version = "KantoFirst"
    sys_version = ""
    protocol_version = "HTTP/1.1"
    files = {}
    link = None  # a link_relay.Relay when started with --link; else /link is a 404

    def _respond(self, send_body):
        if self.timeout is None:
            return self._send(send_body)
        # --link: the per-read timeout bounds the request headers (slowloris), but Python
        # applies a socket timeout to a whole sendall, so lift it while a download is written
        self.connection.settimeout(None)
        try:
            return self._send(send_body)
        finally:
            self.connection.settimeout(self.timeout)

    def _send(self, send_body):
        entry = self.files.get(self.path.split("?", 1)[0])
        if entry is None:
            body = b"404\n"
            self.send_response(404)
            self.send_header("Content-Type", "text/plain; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            if send_body:
                self.wfile.write(body)
            return
        body, ctype, cacheable = entry
        self.send_response(200)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        if isinstance(cacheable, str):
            self.send_header("Cache-Control", cacheable)
        else:
            self.send_header("Cache-Control", "max-age=3600" if cacheable else "no-store")
        self.send_header("X-Content-Type-Options", "nosniff")
        self.end_headers()
        if send_body:
            self.wfile.write(body)

    def do_GET(self):
        if self.link is not None and self.path.split("?", 1)[0] == "/link":
            self.log_link()
            return self.link.handle(self)
        self._respond(True)

    def do_HEAD(self):
        self._respond(False)

    def log_link(self):  # no IP and no query string: the relay logs its own events
        sys.stderr.write('- "GET /link"\n')

    def log_message(self, fmt, *args):  # one line per request, on stderr
        sys.stderr.write("%s %s\n" % (self.address_string(), fmt % args))


def main():
    parser = argparse.ArgumentParser(description="Serve the Kanto First web player.")
    parser.add_argument("--rom", default="kanto-first.gbc", help="path to the .gbc ROM (default: ./kanto-first.gbc)")
    parser.add_argument("--host", default="127.0.0.1", help="bind address (default: 127.0.0.1)")
    parser.add_argument("--port", type=int, default=8080, help="port (default: 8080; 0 = any free port)")
    parser.add_argument("--link", action="store_true", help="also serve the link relay at /link (LK1d)")
    parser.add_argument("--link-origin", action="append", default=[], metavar="ORIGIN",
                        help="extra allowed Origin for /link, e.g. http://127.0.0.1:8080 (repeatable)")
    parser.add_argument("--link-cap", action="append", default=[], metavar="NAME=VALUE",
                        help="override a relay cap (see CAPS in link_relay.py; repeatable)")
    args = parser.parse_args()

    Handler.files = load_files(args.rom)
    if args.link:
        import link_relay
        Handler.link = link_relay.Relay(link_relay.DEFAULT_ORIGINS + tuple(args.link_origin),
                                        link_relay.parse_caps(args.link_cap)).start()
        # bounds the HTTP header phase before an upgrade (slowloris): a per-read socket timeout
        Handler.timeout = Handler.link.caps["handshake_s"]
    elif args.link_origin or args.link_cap:
        parser.error("--link-origin and --link-cap need --link")
    rom_bytes = len(Handler.files[ROM_PATH][0])
    server = http.server.ThreadingHTTPServer((args.host, args.port), Handler)
    print("Kanto First on http://%s:%d/  (%d files, ROM %d bytes from %s)%s"
          % (args.host, server.server_address[1], len(Handler.files) - 1, rom_bytes, args.rom,
             "  link relay at /link" if args.link else ""), flush=True)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        if Handler.link is not None:
            Handler.link.stop()
        server.server_close()


if __name__ == "__main__":
    main()
