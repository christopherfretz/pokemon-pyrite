  function normalizeSram(bytes) {
    var size = T.sav.size;
    if (bytes.length === size) { return bytes.slice(0); }
    var out = new Uint8Array(size);
    out.set(bytes.subarray(0, Math.min(bytes.length, size)));
    return out;
  }

  function off(name) {
    var f = T.fields[name];
    if (!f) { throw new Error('tables.json has no field ' + name); }
    return f[0];
  }
  function len(name) { return T.fields[name][1]; }
  function rd8(name) { return sav[off(name)]; }
  function wr8(name, v) { sav[off(name)] = v & 0xff; }
  function rdBE(name, n) {
    var o = off(name), v = 0;
    for (var i = 0; i < n; i++) { v = v * 256 + sav[o + i]; }
    return v;
  }
  function wrBE(name, n, v) {
    var o = off(name);
    for (var i = n - 1; i >= 0; i--) { sav[o + i] = v & 0xff; v = Math.floor(v / 256); }
  }

  function checksumOf(c) {
    var s = 0;
    for (var i = c.gameData; i < c.gameDataEnd; i++) { s = (s + sav[i]) & 0xffff; }
    return s;
  }
  function copyOk(c) {
    var stored = sav[c.checksum] | (sav[c.checksum + 1] << 8);
    return stored === checksumOf(c) &&
      sav[c.checkValue1] === T.sav.checkValue1 &&
      sav[c.checkValue2] === T.sav.checkValue2;
  }

  /* Write the save the way _SaveGameData does: the backup copy is a verbatim
     duplicate of the primary (the whole span is a uniform -0x0E00 shift, and
     gen_tables.py asserts that at build time), both magic bytes set, both
     checksums recomputed.  Editing only one copy is the classic way to lose an
     edit: the loader falls back to the other copy and silently reverts you. */
  function finalize() {
    var P = T.sav.copies[0], B = T.sav.copies[1];
    var from = P.options, to = P.checkValue2 + 1;
    sav.set(sav.subarray(from, to), from + T.sav.backupDelta);
    [P, B].forEach(function (c) {
      sav[c.checkValue1] = T.sav.checkValue1;
      sav[c.checkValue2] = T.sav.checkValue2;
      var s = checksumOf(c);
      sav[c.checksum] = s & 0xff;
      sav[c.checksum + 1] = (s >> 8) & 0xff;
    });
  }

  // ------------------------------------------------------------- charmap ----

  var decMap = null;
  function decodeTable() {
    if (decMap) { return decMap; }
    decMap = {};
    Object.keys(T.charmap).forEach(function (ch) {
      var b = T.charmap[ch];
      var cur = decMap[b];
      // prefer a plain ASCII spelling when several characters share a byte
      if (cur === undefined || (ch.charCodeAt(0) < 128 && cur.charCodeAt(0) >= 128)) { decMap[b] = ch; }
    });
    return decMap;
  }
  var TERM = 0x50;   // "@"
  function decodeName(o, n) {
    var m = decodeTable(), out = '';
    for (var i = 0; i < n; i++) {
      var b = sav[o + i];
      if (b === TERM || b === 0) { break; }
      out += m[b] !== undefined ? m[b] : '?';
    }
    return out;
  }
  function encodeName(str, o, n) {
    var i = 0, j = 0;
    for (; i < str.length && j < n - 1; i++) {
      var ch = str[i];
      var b = T.charmap[ch];
      if (b === undefined) { b = T.charmap[ch.toUpperCase()]; }
      if (b === undefined) { continue; }
      sav[o + j] = b;
      j++;
    }
    for (; j < n; j++) { sav[o + j] = TERM; }
  }
  function nameIsEncodable(str) {
    for (var i = 0; i < str.length; i++) {
      if (T.charmap[str[i]] === undefined && T.charmap[str[i].toUpperCase()] === undefined) { return false; }
    }
    return true;
  }

  // ------------------------------------------------------ stats / exp -------
  /* CalcMonStatC (engine/pokemon/move_mon.asm) and CalcExpAtLevel
     (engine/pokemon/experience.asm), transcribed.  Inputs come out of the ROM
     image, so these stay correct across rebalances of the base-stat table. */

  function baseStat(species, key) {
    var bs = T.baseStats;
    return rom[bs.rom + (species - 1) * bs.stride + bs.fields[key]];
  }

  function sqrtIndex(v) {
    // GetSquareRoot: the index of the first square that is not lower than v.
    var n = T.limits.numSquareRoots;
    for (var b = 1; b < n; b++) { if (b * b >= v) { return b; } }
    return n;
  }

  var STAT_KEYS = ['hp', 'atk', 'def', 'spd', 'sat', 'sdf'];

  function dvFor(dvs, idx) {
    var atk = (dvs[0] >> 4) & 0xf, def = dvs[0] & 0xf;
    var spd = (dvs[1] >> 4) & 0xf, spc = dvs[1] & 0xf;
    if (idx === 1) { return atk; }
    if (idx === 2) { return def; }
    if (idx === 3) { return spd; }
    if (idx === 4 || idx === 5) { return spc; }
    return ((atk & 1) << 3) | ((def & 1) << 2) | ((spd & 1) << 1) | (spc & 1);
  }

  function calcStat(species, idx, dvs, statExpWords, level) {
    var base = baseStat(species, STAT_KEYS[idx]);
    var dv = dvFor(dvs, idx);
    // STAT_SDEF shares STAT_SATK's stat experience word
    var se = statExpWords[idx === 5 ? 4 : (idx === 0 ? 0 : idx)] || 0;
    var x = (base + dv) * 2 + (sqrtIndex(se) >> 2);
    var v = Math.floor(x * level / 100);
    v += idx === 0 ? (level + T.limits.statMinHP) : T.limits.statMinNormal;
    return Math.min(v, T.limits.maxStatValue);
  }

  function expAtLevel(species, level) {
    var g = rom[T.baseStats.rom + (species - 1) * T.baseStats.stride + T.baseStats.fields.growthRate];
    var r = T.growthRates[g];
    if (!r) { return 0; }
    var n = level;
    // (a/b)*n^3 + c*n^2 + d*n - e, the cubic term truncated like the game's divide
    var v = Math.floor(r[0] * n * n * n / r[1]) + r[2] * n * n + r[3] * n - r[4];
    // The game underflows here for a level-1 Medium Slow mon (a documented
    // bug); clamping is the sane thing for an editor to do instead.
    if (v < 0) { v = 0; }
    return Math.min(v, 0xffffff);
  }

  function movePP(move) {
    if (!move) { return 0; }
    var ms = T.moveStats;
    return rom[ms.rom + (move - 1) * ms.stride + ms.fields.pp];
  }

  // -------------------------------------------------------- the party ------

  var P = null;   // T.party shorthand

  function monField(mon, key) { return mon[P.mon[key]]; }
  function monWord(mon, key) { return (mon[P.mon[key]] << 8) | mon[P.mon[key] + 1]; }
  function setMonWord(mon, key, v) {
    mon[P.mon[key]] = (v >> 8) & 0xff;
    mon[P.mon[key] + 1] = v & 0xff;
  }

  function statExpWords(mon) {
    var o = P.mon.statExp, out = [];
    for (var i = 0; i < 5; i++) { out.push((mon[o + i * 2] << 8) | mon[o + i * 2 + 1]); }
    return out;
  }

  /* Recompute max HP and the five stats, set EXP to the minimum for the
     mon's level, refill PP, and (heal) put current HP at max. */
  function recalcMon(slot, heal) {
    var mon = slot.mon;
    var species = mon[P.mon.species];
    var level = mon[P.mon.level];
    var dvs = [mon[P.mon.dvs], mon[P.mon.dvs + 1]];
    var se = statExpWords(mon);
    var maxHp = calcStat(species, 0, dvs, se, level);
    setMonWord(mon, 'maxHp', maxHp);
    for (var i = 1; i < 6; i++) {
      var v = calcStat(species, i, dvs, se, level);
      mon[P.mon.stats + (i - 1) * 2] = (v >> 8) & 0xff;
      mon[P.mon.stats + (i - 1) * 2 + 1] = v & 0xff;
    }
    var xp = expAtLevel(species, level);   // exp is a 3-byte big-endian field
    mon[P.mon.exp] = (xp >> 16) & 0xff;
    mon[P.mon.exp + 1] = (xp >> 8) & 0xff;
    mon[P.mon.exp + 2] = xp & 0xff;
    for (var m = 0; m < P.numMoves; m++) { mon[P.mon.pp + m] = movePP(mon[P.mon.moves + m]); }
    if (heal) {
      setMonWord(mon, 'hp', maxHp);
      mon[P.mon.status] = 0;
    } else if (monWord(mon, 'hp') > maxHp) {
      setMonWord(mon, 'hp', maxHp);
    }
  }

  function newMon(species, level) {
    var mon = new Uint8Array(P.stride);
    mon[P.mon.species] = species;
    mon[P.mon.level] = level;
    mon[P.mon.dvs] = 0xff;             // 15 in every DV: predictable, and good
    mon[P.mon.dvs + 1] = 0xff;
    mon[P.mon.happiness] = T.limits.baseHappiness;
    mon[P.mon.id] = sav[off('wPlayerID')];
    mon[P.mon.id + 1] = sav[off('wPlayerID') + 1];
    return mon;
  }

  function readParty() {
    party = [];
    var count = rd8('wPartyCount');
    var mons = off('wPartyMons'), ots = off('wPartyMonOTs'), nicks = off('wPartyMonNicknames');
    for (var i = 0; i < P.length; i++) {
      if (i >= count) { party.push(null); continue; }
      party.push({
        mon: sav.slice(mons + i * P.stride, mons + (i + 1) * P.stride),
        ot: sav.slice(ots + i * P.otLength, ots + (i + 1) * P.otLength),
        nick: sav.slice(nicks + i * P.nickLength, nicks + (i + 1) * P.nickLength)
      });
    }
  }

  function writeParty() {
    var filled = party.filter(function (s) { return s; });
    var mons = off('wPartyMons'), ots = off('wPartyMonOTs'), nicks = off('wPartyMonNicknames');
    var spec = off('wPartySpecies');
    sav[off('wPartyCount')] = filled.length;
    for (var i = 0; i < P.length; i++) {
      var s = filled[i];
      sav[spec + i] = s ? s.mon[P.mon.species] : 0;
      if (s) {
        sav.set(s.mon, mons + i * P.stride);
        sav.set(s.ot, ots + i * P.otLength);
        sav.set(s.nick, nicks + i * P.nickLength);
      } else {
        sav.fill(0, mons + i * P.stride, mons + (i + 1) * P.stride);
        sav.fill(TERM, ots + i * P.otLength, ots + (i + 1) * P.otLength);
        sav.fill(TERM, nicks + i * P.nickLength, nicks + (i + 1) * P.nickLength);
      }
    }
    sav[spec + filled.length] = 0xff;   // the party list's terminator
    // keep the UI's model in the compacted order the cartridge uses
    party = filled.concat(new Array(P.length - filled.length).fill(null));
  }

  // ---------------------------------------------------------------- bag -----

  /* Pocket layout (engine/items/pack.asm + the wNum*/ /* fields):
     a count byte, then `entry` bytes per slot, then a $ff terminator.  The
     TM/HM pocket is different: wTMsHMs is a flat quantity-per-TM array. */
  var POCKETS = [
    { id: 'item', label: 'Items', count: 'wNumItems', list: 'wItems', entry: 2, cap: 'maxItems' },
    { id: 'ball', label: 'Balls', count: 'wNumBalls', list: 'wBalls', entry: 2, cap: 'maxBalls' },
    { id: 'key', label: 'Key items', count: 'wNumKeyItems', list: 'wKeyItems', entry: 1, cap: 'maxKeyItems' }
  ];

  function readBag() {
    bag = {};
    POCKETS.forEach(function (p) {
      var n = Math.min(sav[off(p.count)], T.limits[p.cap]);
      var o = off(p.list), out = [];
      for (var i = 0; i < n; i++) {
        var id = sav[o + i * p.entry];
        if (!id || id === 0xff) { break; }
        out.push({ id: id, qty: p.entry === 2 ? sav[o + i * p.entry + 1] : 1 });
      }
      bag[p.id] = out;
    });
    bag.tm = Array.prototype.slice.call(sav.subarray(off('wTMsHMs'), off('wTMsHMs') + len('wTMsHMs')));
  }

  function writeBag() {
    POCKETS.forEach(function (p) {
      var o = off(p.list), cap = T.limits[p.cap], list = bag[p.id].slice(0, cap);
      sav[off(p.count)] = list.length;
      for (var i = 0; i < cap; i++) {
        if (i < list.length) {
          sav[o + i * p.entry] = list[i].id;
          if (p.entry === 2) { sav[o + i * p.entry + 1] = list[i].qty; }
        } else {
          sav[o + i * p.entry] = 0;
          if (p.entry === 2) { sav[o + i * p.entry + 1] = 0; }
        }
      }
      sav[o + list.length * p.entry] = 0xff;
    });
    sav.set(bag.tm, off('wTMsHMs'));
  }

