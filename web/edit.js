  // "Put me in X" is more than wMapGroup/wMapNumber/wXCoord/wYCoord.  The
  // continue path (MapSetupScript_Continue, data/maps/setup_scripts.asm) calls
  // LoadMapAttributes_SkipObjects -- it never runs SpawnPlayer and never loads
  // the new map's object events -- and then LoadConnectionBlockData copies the
  // saved 6x5 metatile window (wScreenSave) straight back over the blocks
  // around the player.  Everything below is therefore state the game would
  // normally have built while walking, and that we have to build ourselves:
  //   * the player's (and the follower's) object struct + map object, which
  //     otherwise still hold the OLD map's coordinates -- the player ends up
  //     off-map and cannot take a single step;
  //   * wScreenSave, which otherwise paints a 6x5 patch of the old map over
  //     the new one (gen_tables.py precomputes the right window from the ROM);
  //   * the old map's NPCs, which would otherwise linger in wMapObjects /
  //     wObjectStructs.  We evict them; the real ones appear as soon as the
  //     player leaves the map and comes back.
  function putMeIn(s) {
    wr8('wMapGroup', s.group);
    wr8('wMapNumber', s.number);
    wr8('wXCoord', s.x);
    wr8('wYCoord', s.y);
    wr8('wWarpNumber', 0);        // not mid-warp: the continue path uses coords
    // PlayerSpawn_ConvertCoords (engine/overworld/player_object.asm): map
    // object coords are tile coords + 4.
    var mx = (s.x + 4) & 0xff, my = (s.y + 4) & 0xff;
    var st = T.objects.standing;   // STANDING, constants/ram_constants.asm
    wr8('wPlayerObjectXCoord', mx);
    wr8('wPlayerObjectYCoord', my);
    // CopyTempObjectToObjectStruct: INIT/MAP coords, SPRITE_X/Y centred,
    // STEP_TYPE_RESET, FACING = STANDING.  The motion members matter as much
    // as the coordinates: a save captured mid-step resumes that step on the
    // new map, which on an open tile walks the player off it.
    ['wPlayer', 'wFollower'].forEach(function (pfx) {
      var geom = {
        MapX: mx, MapY: my, LastMapX: mx, LastMapY: my, InitX: mx, InitY: my,
        SpriteX: 0x40, SpriteY: 0x40, SpriteXOffset: 0, SpriteYOffset: 0,
        Walking: st, Facing: st, Direction: 0, StepType: 0, StepDuration: 0,
        StepFrame: 0, TileCollision: 0, LastTile: 0, MovementIndex: 0,
        StepIndex: 0, Field1d: 0, Field1e: 0, JumpHeight: 0
      };
      Object.keys(geom).forEach(function (k) {
        if (T.fields[pfx + k]) { wr8(pfx + k, geom[k]); }
      });
    });

    // the saved scene pointer still aims at the OLD map's scene id; point it
    // at the new map's scene variable (0 = this map has no scene scripts)
    var sp = off('wCurMapSceneScriptPointer');
    sav[sp] = s.scene & 0xff;
    sav[sp + 1] = (s.scene >> 8) & 0xff;

    // the metatile window the game would have buffered standing on that tile
    var o = off('wScreenSave'), n = Math.min(s.screen.length, len('wScreenSave'));
    for (var i = 0; i < n; i++) { sav[o + i] = s.screen[i] & 0xff; }

    // evict the old map's NPCs (object 0 is the player, struct 13 the follower)
    var ob = T.objects;
    for (i = 1; i < ob.numObjects; i++) {
      sav.fill(0, off('wMapObjects') + i * ob.mapObjectLength,
               off('wMapObjects') + (i + 1) * ob.mapObjectLength);
    }
    for (i = 1; i < ob.followerIndex; i++) {
      sav.fill(0, off('wObjectStructs') + i * ob.structLength,
               off('wObjectStructs') + (i + 1) * ob.structLength);
    }
    // arriving somewhere is what the game records for fly / blackout
    wr8('wLastSpawnMapGroup', s.group);
    wr8('wLastSpawnMapNumber', s.number);
    var vb = off('wVisitedSpawns') + (s.index >> 3);
    if (s.index >> 3 < len('wVisitedSpawns')) { sav[vb] |= 1 << (s.index & 7); }
  }

