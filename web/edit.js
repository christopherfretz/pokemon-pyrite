/* Kanto First - save editor for the browser player.
 *
 * Same origin, same IndexedDB, same battery record as app.js: this page reads
 * `battery:<titleKey>`, lets you change the parts of the save a player might
 * reasonably want to change, writes BOTH save copies back with fresh
 * checksums, deletes the `resume:` snapshot (otherwise the emulator would
 * restore the pre-edit machine state and your edit would vanish) and sends you
 * back to the player, which then power-ons from the edited cartridge RAM.
 *
 * Nothing about the save format is hardcoded here.  web/tables.json is
 * generated by web/gen_tables.py from pokecrystal.sym + constants/*.asm at
 * build time (`make crystal`), and carries the SRAM offsets, the party struct
 * layout, the name tables, the base-stat/growth-rate table addresses and the
 * sha256 of the ROM it was generated from.  If the loaded ROM's sha does not
 * match that stamp the editor refuses to write anything: the offsets would be
 * for a different build.
 *
 * The one thing that is NOT derived is arithmetic: the stat and experience
 * formulas below are a transcription of CalcMonStatC and CalcExpAtLevel
 * (engine/pokemon/move_mon.asm, engine/pokemon/experience.asm).  They read
 * their inputs out of the ROM image this page already fetched.
 */
