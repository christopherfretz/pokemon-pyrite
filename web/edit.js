  function sha256Sync(bytes) {
    var h = [0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19];
    var len = bytes.length, withPad = ((len + 9 + 63) >> 6) << 6;
    var m = new Uint8Array(withPad);
    m.set(bytes);
    m[len] = 0x80;
    var bits = len * 8, i;
    m[withPad - 1] = bits & 0xff;
    m[withPad - 2] = (bits / 0x100) & 0xff;
    m[withPad - 3] = (bits / 0x10000) & 0xff;
    m[withPad - 4] = (bits / 0x1000000) & 0xff;
    m[withPad - 5] = (bits / 0x100000000) & 0xff;
    m[withPad - 6] = (bits / 0x10000000000) & 0xff;
    var w = new Int32Array(64);
    for (var off = 0; off < withPad; off += 64) {
      for (i = 0; i < 16; i++) {
        w[i] = (m[off + i * 4] << 24) | (m[off + i * 4 + 1] << 16) | (m[off + i * 4 + 2] << 8) | m[off + i * 4 + 3];
      }
      for (i = 16; i < 64; i++) {
        var g0 = w[i - 15], g1 = w[i - 2];
        var s0 = ((g0 >>> 7) | (g0 << 25)) ^ ((g0 >>> 18) | (g0 << 14)) ^ (g0 >>> 3);
        var s1 = ((g1 >>> 17) | (g1 << 15)) ^ ((g1 >>> 19) | (g1 << 13)) ^ (g1 >>> 10);
        w[i] = (w[i - 16] + s0 + w[i - 7] + s1) | 0;
      }
      var a = h[0], b = h[1], c = h[2], d = h[3], e = h[4], f = h[5], gg = h[6], hh = h[7];
      for (i = 0; i < 64; i++) {
        var S1 = ((e >>> 6) | (e << 26)) ^ ((e >>> 11) | (e << 21)) ^ ((e >>> 25) | (e << 7));
        var ch = (e & f) ^ (~e & gg);
        var t1 = (hh + S1 + ch + KK[i] + w[i]) | 0;
        var S0 = ((a >>> 2) | (a << 30)) ^ ((a >>> 13) | (a << 19)) ^ ((a >>> 22) | (a << 10));
        var maj = (a & b) ^ (a & c) ^ (b & c);
        var t2 = (S0 + maj) | 0;
        hh = gg; gg = f; f = e; e = (d + t1) | 0; d = c; c = b; b = a; a = (t1 + t2) | 0;
      }
      h[0] = (h[0] + a) | 0; h[1] = (h[1] + b) | 0; h[2] = (h[2] + c) | 0; h[3] = (h[3] + d) | 0;
      h[4] = (h[4] + e) | 0; h[5] = (h[5] + f) | 0; h[6] = (h[6] + gg) | 0; h[7] = (h[7] + hh) | 0;
    }
    var out = '';
    for (i = 0; i < 8; i++) { out += ('00000000' + (h[i] >>> 0).toString(16)).slice(-8); }
    return out;
  }

  function sha256(bytes) {
    if (window.crypto && window.crypto.subtle && window.crypto.subtle.digest) {
      var copy = bytes.slice(0);
      return window.crypto.subtle.digest('SHA-256', copy.buffer).then(function (buf) {
        var v = new Uint8Array(buf), s = '', i;
        for (i = 0; i < v.length; i++) { s += (v[i] < 16 ? '0' : '') + v[i].toString(16); }
        return s;
      }).catch(function () { return sha256Sync(bytes); });
    }
    return Promise.resolve(sha256Sync(bytes));
  }

  // ------------------------------------------------------------ IndexedDB ---

  var dbPromise = null;
  function db() {
    if (!dbPromise) {
      dbPromise = new Promise(function (resolve, reject) {
        var req = indexedDB.open(DB_NAME, DB_VERSION);
        req.onupgradeneeded = function () {
          if (!req.result.objectStoreNames.contains(STORE)) { req.result.createObjectStore(STORE); }
        };
        req.onsuccess = function () { resolve(req.result); };
        req.onerror = function () { reject(req.error); };
        req.onblocked = function () { reject(new Error('IndexedDB blocked')); };
      });
    }
    return dbPromise;
  }
  function tx(mode, fn) {
    return db().then(function (d) {
      return new Promise(function (resolve, reject) {
        var t = d.transaction(STORE, mode);
        var req = fn(t.objectStore(STORE));
        t.oncomplete = function () { resolve(req ? req.result : undefined); };
        t.onerror = function () { reject(t.error); };
        t.onabort = function () { reject(t.error); };
      });
    });
  }
  function kvGet(k) { return tx('readonly', function (s) { return s.get(k); }); }
  function kvPut(k, v) { return tx('readwrite', function (s) { return s.put(v, k); }); }
  function kvDel(k) { return tx('readwrite', function (s) { return s.delete(k); }); }

  function batteryKey() { return 'battery:' + titleKey; }
  function backupKey() { return 'battery-backup:' + titleKey; }
  function resumeKey() { return 'resume:' + titleKey; }

  /* Same save-region signature app.js stores in every battery/resume record:
     FNV-1a over cartridge RAM from $600 on (past sScratch, the decompression
     scratch area).  Keep in step with sig()/saveSig() in app.js. */
  function saveSig(ram) {
    var bytes = ram.subarray(Math.min(0x600, ram.length));
    var h = 0x811c9dc5;
    for (var i = 0; i < bytes.length; i++) {
      h ^= bytes[i];
      h = (h + ((h << 1) + (h << 4) + (h << 7) + (h << 8) + (h << 24))) >>> 0;
    }
    return h + ':' + bytes.length;
  }

  // ------------------------------------------------------------- ROM load ---

  function titleKeyOf(r) {
    var t = '';
    for (var i = 0x134; i < 0x144; i++) {
      var c = r[i];
      if (c >= 0x20 && c <= 0x7e) { t += String.fromCharCode(c); }
    }
    return (t.replace(/[^A-Za-z0-9_.-]/g, '') || 'UNKNOWN') + '-' + r[0x147].toString(16);
  }

