#!/usr/bin/env python3
"""Generate web/sw.js (the offline service worker) from web/sw.template.js.

Run by `make crystal` (rule `web/sw.js` in the Makefile).  The worker
precaches one atomic bundle per build; this script stamps it with:

  build    BUILD_REV (build_rev.txt, the short commit hash on the title screen)
  rom      sha256 of the ROM, served by the page as kanto-first.gbc
  files    {bundle path: sha256} for every precached file; the worker refuses
           to install unless every fetched file matches
  presets  {presets/<name>.sav: sha256}, cached on first use, only on a match
  version  12 hex of a sha256 over all of the above + the template; the cache
           is named kf-<version>

Output is deterministic (no timestamps), so an unchanged build regenerates a
byte-identical sw.js and the browser sees no update.

    python3 web/gen_sw.py --root . --out web/sw.js
    python3 web/gen_sw.py --root . --web /some/copy/of/web --build-rev test123 --out /some/copy/of/web/sw.js
"""

import argparse
import hashlib
import json
import os
import sys

# Bundle path (relative to the page) -> source path (relative to --web), or
# None for the ROM, which comes from --rom.
BUNDLE = [
    "index.html",
    "app.js",
    "offline.js",
    "style.css",
    "manifest.webmanifest",
    "icon-192.png",
    "icon-512.png",
    "vendor/binjgb/binjgb.js",
    "vendor/binjgb/binjgb.wasm",
    "kanto-first.gbc",
    "tables.json",
    "edit.html",
    "edit.js",
    "presets/manifest.json",
]
ROM_NAME = "kanto-first.gbc"
PLACEHOLDER = "/*@KF_BUNDLE@*/null"


def sha_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--root", default=os.path.dirname(here), help="hack/ checkout root")
    ap.add_argument("--web", default=None, help="web directory to hash (default: <root>/web)")
    ap.add_argument("--rom", default=None, help="ROM served as kanto-first.gbc (default: <root>/pokecrystal.gbc)")
    ap.add_argument("--build-rev", default=None, help="override build_rev.txt")
    ap.add_argument("--template", default=None, help="default: <web>/sw.template.js")
    ap.add_argument("--out", default=None, help="default: <web>/sw.js")
    a = ap.parse_args()

    web = a.web or os.path.join(a.root, "web")
    rom = a.rom or os.path.join(a.root, "pokecrystal.gbc")
    template = a.template or os.path.join(web, "sw.template.js")
    out = a.out or os.path.join(web, "sw.js")

    build = a.build_rev
    if build is None:
        rev_file = os.path.join(a.root, "build_rev.txt")
        build = open(rev_file, encoding="utf-8").read().strip() if os.path.exists(rev_file) else "unknown"

    files = {}
    for rel in BUNDLE:
        src = rom if rel == ROM_NAME else os.path.join(web, rel)
        if not os.path.isfile(src):
            sys.exit("gen_sw: missing bundle file %s" % src)
        files[rel] = sha_file(src)

    presets = {}
    pdir = os.path.join(web, "presets")
    if os.path.isdir(pdir):
        for name in sorted(os.listdir(pdir)):
            if name.lower().endswith(".sav") and os.path.isfile(os.path.join(pdir, name)):
                presets["presets/" + name] = sha_file(os.path.join(pdir, name))

    with open(template, encoding="utf-8") as f:
        tpl = f.read()
    if tpl.count(PLACEHOLDER) != 1:
        sys.exit("gen_sw: %s must contain %s exactly once" % (template, PLACEHOLDER))

    stamp = {"build": build, "rom": files[ROM_NAME], "files": files, "presets": presets}
    canon = json.dumps(stamp, sort_keys=True, separators=(",", ":"))
    stamp["version"] = hashlib.sha256((canon + "\n" + tpl).encode("utf-8")).hexdigest()[:12]

    body = json.dumps(stamp, sort_keys=True, indent=1)
    js = ("/* GENERATED by web/gen_sw.py from web/sw.template.js - do not edit. */\n"
          + tpl.replace(PLACEHOLDER, body))
    with open(out, "w", encoding="utf-8") as f:
        f.write(js)
    print("gen_sw: %s  build %s  rom %s  cache kf-%s  (%d files, %d presets)"
          % (out, build, files[ROM_NAME][:12], stamp["version"], len(files), len(presets)))


if __name__ == "__main__":
    main()
